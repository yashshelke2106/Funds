# ---------- guards: the templates' prose depends on these facts, so a change must stop the build

def test_stops_if_flagged_fund_count_changes(frames):
    f = dict(frames)
    c = f["cls"].copy()
    c.loc[c.fund_id == "sundaram_lc", "class_main"] = "closet_underperforming"
    f["cls"] = c
    with pytest.raises(ReportError, match="exactly one"):
        numbers.key_numbers(f)


def test_stops_if_class_summary_disagrees(frames):
    f = dict(frames)
    s = f["summary"].copy()
    s.loc[s.class_main == "closet", "funds"] = 8
    f["summary"] = s
    with pytest.raises(ReportError, match="disagree"):
        numbers.key_numbers(f)


def test_stops_if_index_fund_no_longer_trails(frames):
    f = dict(frames)
    r = f["rolling"].copy()
    r.loc[(r.fund_id == "bandhan_n100") & (r.plan == "regular"), "excess_ann"] = 0.001
    f["rolling"] = r
    with pytest.raises(ReportError, match="no longer"):
        numbers.key_numbers(f)


