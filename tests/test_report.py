# ---------- formatting

def test_num_uses_real_minus_and_never_prints_negative_zero():
    assert numbers.num(-1.567) == MINUS + "1.57"
    assert numbers.num(-0.004) == "0.00"
    assert numbers.signed(0.2204) == "+0.22" and numbers.signed(-0.004) == "0.00"


def test_pct_converts_fraction_to_percent_number():
    assert numbers.pct(0.0157) == "1.57"
    assert numbers.spct(-0.0157123) == MINUS + "1.57" and numbers.spct(0.049036) == "+4.90"


def test_indian_grouping():
    assert numbers.indian(999) == "999" and numbers.indian(1000) == "1,000"
    assert numbers.indian(123456.7) == "1,23,457"
    assert numbers.indian(-1234567.891, 2) == MINUS + "12,34,567.89"
    assert numbers.indian(184493.4) == "1,84,493"


def test_t_stat_is_information_ratio_times_root_years():
    assert numbers.t_stat(0.5, 252 * 4) == pytest.approx(1.0)        # 4 years -> x2
    assert numbers.t_stat(-0.614793, 491) == pytest.approx(-0.614793 * math.sqrt(491 / 252))


def test_rank_phrase_and_names():
    assert numbers.rank_phrase(1, 17) == "the lowest of the 17"
    assert numbers.rank_phrase(2, 17) == "the 2nd lowest of the 17" and numbers.rank_phrase(11, 17) == "the 11th lowest of the 17"
    assert numbers.names(["A"]) == "A" and numbers.names(["A", "B", "C"]) == "A, B and C"


# ---------- renderer

def test_render_fills_placeholders():
    assert render.render("a {{x}} b {{ y }} {{x}}", {"x": "1", "y": "2"}) == "a 1 b 2 1"


def test_render_stops_on_unknown_placeholder():
    with pytest.raises(ReportError, match="made_up"):
        render.render("value {{made_up}}", {"x": "1"})


def test_render_stops_on_malformed_placeholder():
    with pytest.raises(ReportError, match="malformed"):
        render.render("value {{Bad Name}}", {"x": "1"})


def test_run_writes_title_then_banner(tmp_path):
    (tmp_path / "t.md").write_text("# Title\n\nbody {{x}}\n", encoding="utf-8")
    out = render.run(templates=tmp_path, targets={"t.md": tmp_path / "out" / "t.md"}, values={"x": "7"})
    text = out["t.md"].read_text(encoding="utf-8").splitlines()
    assert text[0] == "# Title" and text[1] == "" and text[2].startswith("<!-- Generated by") and text[-1] == "body 7"


def test_run_stops_when_template_missing(tmp_path):
    with pytest.raises(ReportError, match="template missing"):
        render.run(templates=tmp_path, targets={"nope.md": tmp_path / "nope.md"}, values={})


